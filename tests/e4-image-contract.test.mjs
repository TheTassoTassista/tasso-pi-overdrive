  assert.match(preflight, /needs\.e4-image-qualification\.result == 'success'/u);
  assert.match(preflight, /E4_CERTIFIED_IMAGE_DIGEST: \$\{\{ needs\.e4-image-qualification\.outputs\.digest \}\}/u);
